/**
 * Safe localization helper: Returns the string for the given language pack,
 * falling back cleanly to English (LOCALIZED_LANGUAGES.en), NEVER hardcoding Hindi or "Doctor AI".
 */
export function getLocalizedKioskText(
  langCode: string,
  key: keyof LanguagePack,
  fallbackEn?: string
): string {
  const pack = LOCALIZED_LANGUAGES[langCode];
  if (pack && pack[key]) {
    return pack[key] as string;
  }
  const enPack = LOCALIZED_LANGUAGES.en;
  if (enPack && enPack[key]) {
    return enPack[key] as string;
  }
  return fallbackEn || '';
}
